const md5 = (buf) => crypto.createHash('md5').update(buf).digest('hex');

async function getJson(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url} -> ${r.status}`);
  return r.json();
}

async function download(url, rel, expectedMd5 = null, expectedSize = null) {
  const out = path.join(ROOT, rel);
  if (fs.existsSync(out)) {
    const buf = fs.readFileSync(out);
    if ((!expectedMd5 || md5(buf) === expectedMd5) && (!expectedSize || buf.length === expectedSize)) return { rel, bytes: buf.length, cached: true };
  }
  const r = await fetch(url);
  if (!r.ok) throw new Error(`download ${url} -> ${r.status}`);
  const buf = Buffer.from(await r.arrayBuffer());
  if (expectedMd5 && md5(buf) !== expectedMd5) throw new Error(`checksum mismatch for ${rel}`);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, buf);
  return { rel, bytes: buf.length, cached: false };
}

async function pool(items, n, fn) {
  const results = [];
  let i = 0;
  await Promise.all(Array.from({ length: n }, async () => {
    while (i < items.length) {
      const k = i++;
      results[k] = await fn(items[k]);
    }
  }));
  return results;
}

const manifest = { generated: new Date().toISOString(), note: 'All paths are relative to /assets/. Generated by scripts/fetch-assets.mjs.', textures: {}, hdri: {}, models: {}, characters: {} };
let totalBytes = 0;
const log = (s) => process.stdout.write(`${s}\n`);

// ---- textures
await pool(Object.entries(TEXTURES), 4, async ([name, id]) => {
  const f = await getJson(`${API}/files/${id}`);
  const pick = (key) => f[key] && f[key]['1k'] && f[key]['1k'].jpg;
  const maps = { diff: pick('Diffuse'), nor: pick('nor_gl'), arm: pick('arm') };
  const files = {};
  for (const [k, v] of Object.entries(maps)) {
    if (!v) throw new Error(`${id}: missing ${k}`);
    const rel = `textures/${id}/${id}_${k}_1k.jpg`;
    const res = await download(v.url, rel, v.md5, v.size);
    totalBytes += res.bytes;
    files[k] = rel;
  }
  manifest.textures[name] = { source: `https://polyhaven.com/a/${id}`, license: 'CC0', resolution: '1k', files };
  log(`texture ${name.padEnd(14)} ${id}`);
});

// ---- HDRIs
for (const [name, [id, res]] of Object.entries(HDRIS)) {
  const f = await getJson(`${API}/files/${id}`);
  const v = f.hdri[res].hdr;
  const rel = `hdri/${id}_${res}.hdr`;
  const r = await download(v.url, rel, v.md5, v.size);
  totalBytes += r.bytes;
  manifest.hdri[name] = { source: `https://polyhaven.com/a/${id}`, license: 'CC0', resolution: res, file: rel };
  log(`hdri    ${name.padEnd(14)} ${id}`);
}

// ---- models (glTF + bin + textures)
await pool(Object.entries(MODELS), 4, async ([name, id]) => {
  const f = await getJson(`${API}/files/${id}`);
  const g = f.gltf['1k'].gltf;
  const dir = `models/${id}`;
  const gltfRel = `${dir}/${path.basename(new URL(g.url).pathname)}`;
  totalBytes += (await download(g.url, gltfRel, g.md5, g.size)).bytes;
  for (const [incPath, inc] of Object.entries(g.include || {})) {
    totalBytes += (await download(inc.url, `${dir}/${incPath}`, inc.md5, inc.size)).bytes;
  }
  const info = await getJson(`${API}/info/${id}`);
  manifest.models[name] = { source: `https://polyhaven.com/a/${id}`, license: 'CC0', file: gltfRel, polycount: info.polycount, dimensionsMm: info.dimensions };
  log(`model   ${name.padEnd(14)} ${id} (${info.polycount} polys)`);
});

// ---- project-owned local assets
for (const [name, d] of Object.entries(LOCAL)) {
  const p = path.join(ROOT, d.file);
  if (!fs.existsSync(p)) throw new Error(`missing ${d.file}: rebuild it with: ${d.rebuild}`);
  const buf = fs.readFileSync(p);
  totalBytes += buf.length;
  manifest.characters[name] = { source: d.source, license: d.license, file: d.file, md5: md5(buf) };
  log(`char    ${name} (local)`);
}

// Sort keys for stable output
for (const k of ['textures', 'models']) manifest[k] = Object.fromEntries(Object.entries(manifest[k]).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(path.join(ROOT, 'manifest.json'), JSON.stringify(manifest, null, 2));
log(`\nManifest written. ${Object.keys(manifest.textures).length} texture sets, ${Object.keys(manifest.hdri).length} HDRIs, ${Object.keys(manifest.models).length} models, ${Object.keys(manifest.characters).length} characters. ${(totalBytes / 1e6).toFixed(1)} MB.`);
